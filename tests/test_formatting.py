"""Проверки того, как список каналов превращается в текст для модели.

Счётчик сообщений хаб долго отдавал заниженным, поэтому плагин его не
показывал. После правки серверной части счётчик стал честным и вернулся
в вывод — эти проверки следят, чтобы он выводился только когда осмыслен
и в правильной русской форме.
"""

from __future__ import annotations

import pytest

from teamhub_mcp import _format_channels, _plural_messages


@pytest.mark.parametrize(
    ("count", "expected"),
    [
        (1, "сообщение"),
        (2, "сообщения"),
        (4, "сообщения"),
        (5, "сообщений"),
        (11, "сообщений"),
        (12, "сообщений"),
        (14, "сообщений"),
        (21, "сообщение"),
        (22, "сообщения"),
        (25, "сообщений"),
        (101, "сообщение"),
        (111, "сообщений"),
    ],
)
def test_форма_слова_сообщение(count: int, expected: str) -> None:
    """Числительное согласуется с существительным по правилам русского языка."""
    assert _plural_messages(count) == expected


def test_пустой_список() -> None:
    """Когда каналов нет, модель получает внятный ответ, а не пустую строку."""
    assert _format_channels([]) == "каналов нет"


def test_канал_с_описанием_и_счётчиком() -> None:
    """Обычный случай: имя, описание и число сообщений в скобках."""
    строка = _format_channels(
        [{"name": "general", "description": "Общее", "message_count": 3}]
    )
    assert строка == "general — Общее (3 сообщения)"


def test_канал_без_описания() -> None:
    """Без описания не должно оставаться висящего тире."""
    assert (
        _format_channels([{"name": "general", "message_count": 1}])
        == "general (1 сообщение)"
    )


@pytest.mark.parametrize("count", [0, None, "много"])
def test_счётчик_не_показывается_когда_бессмыслен(count: object) -> None:
    """Ноль, отсутствие и нечисловое значение счётчика молча опускаются.

    Пустой канал незачем помечать «0 сообщений», а непропатченный хаб может
    вернуть что угодно — падать из-за этого плагин не должен.
    """
    строка = _format_channels(
        [{"name": "general", "description": "Общее", "message_count": count}]
    )
    assert строка == "general — Общее"


def test_несколько_каналов_по_строке_на_каждый() -> None:
    """Каналы разделяются переводом строки — так их читает модель."""
    строка = _format_channels(
        [
            {"name": "general", "description": "Общее", "message_count": 2},
            {"name": "motion", "description": "Проект Motion"},
        ]
    )
    assert строка == "general — Общее (2 сообщения)\nmotion — Проект Motion"
